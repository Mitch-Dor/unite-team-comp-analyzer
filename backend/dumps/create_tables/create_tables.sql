	damage_consistency int2 NULL, -- How many seconds it takes for the Pokemon to get another round of damage out. (ADC = 0)
	damage_area text NULL, -- SingleTarget, SmallAOE (Raichu Electro Ball), MediumAOE (A9 Blizzard, Heavy Slam Snorlax), LargeAOE (Venusaur Solarbeam, Miraidon Charge Beam)
	cc int2 NULL, -- 0 = No CC or minor slow, 1 = Small Interrupt (Cinderace Blaze Kick), 2 = Medium Single Stun / Short Group Stun (Muddy Water Vaporeon / Garchomp Rush+Claw), 3 = Long Single Stun / Medium Group Stun (Heavy Slam Snorlax / Volt Tackle Pikachu), 4 = Significant CC to consistently stun large groups or single players for long times, 5 = Multiple significant stuns
