CREATE TABLE public.pokemon_traits (
	pokemon_id int4 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START 1 CACHE 1 NO CYCLE) NOT NULL,
	mobility int2 NULL, -- 0 = No mobility (Venusaur), 1 = Movement buff (Raichu, Pikachu, Tinkaton), 2 = Short Dash on Long CD (able to go over small walls) (Latios, Ninetales), 3 = Long Dash on long CD or Short Dash on Short CD (Feraligatr, Machamp), 4 = Combo of Long Dash on long CD or Short Dash on Short CD or movement buffs (Leafeon / Absol), 5 = Multiple dashes and/or movement buffs (Zoroark / Talonflame)
	"range" int2 NULL, -- 1 = Pokemon must be in melee range to do significant damage, 2 = Pokemon can be short range away (Metagross Gyro Ball), 3 = Pokemon can be a decent distance away (A9 Blizzard / Raichu Electro Ball / Espeon Psyshock), 4 = Somewhat long range (Miraidon charge beam), 5 = Very long range (Inteleon Snipe Shot, Venusaur Solar Beam)
	bulk int2 NULL, -- 1 = Very squishy (Greninja), 2 = Can be OHKO'd but harder (Typhlosion/Sylveon/Absol), 3 = Some decent natural bulk or extra tools (Blaziken/Suicune/Psyduck), 4 = Takes several people to kill (Metagross/Scizor/Mewtwo X/Mamoswine), 5 = Survives against many people for long periods (Goodra/Crustle)
