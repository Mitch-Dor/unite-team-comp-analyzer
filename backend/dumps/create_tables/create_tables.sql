	classification text NULL, -- Class type
	special_attributes _text NULL, -- Special Attributes of a Pokemon that are uncommon like Umbreon's ability to steal shields.
	level_strength _jsonb NULL,
	CONSTRAINT pokemon_traits_pkey PRIMARY KEY (pokemon_id)
